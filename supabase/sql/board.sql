-- 1) 게시글
create table if not exists public.board_posts (
  id           bigint generated by default as identity primary key,
  board        text        not null check (board in ('notice', 'resource')),
  title        text        not null check (char_length(title) between 1 and 200),
  body         text        not null default '' check (char_length(body) <= 50000),
  category     text        check (category is null or char_length(category) <= 30),
  is_important boolean     not null default false,
  attachments  jsonb       not null default '[]'::jsonb check (jsonb_typeof(attachments) = 'array'),
  author       text        check (author is null or char_length(author) <= 40),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  deleted_at   timestamptz
);

create index if not exists board_posts_list_idx
  on public.board_posts (board, is_important desc, created_at desc)
  where deleted_at is null;

alter table public.board_posts enable row level security;

drop policy if exists board_posts_public_read on public.board_posts;
create policy board_posts_public_read on public.board_posts
  for select to anon, authenticated
  using (deleted_at is null);

grant select on public.board_posts to anon, authenticated;

-- 2) 설정 (담당자 공용 암호 해시) — 아무도 직접 읽지 못한다
create table if not exists public.board_settings (
  key        text primary key,
  value      text not null,
  updated_at timestamptz not null default now()
);
alter table public.board_settings enable row level security;

-- 3) 기록 (로그인·쓰기) — 관리용, 아무도 직접 읽지 못한다
create table if not exists public.board_log (
  id       bigint generated always as identity primary key,
  at       timestamptz not null default now(),
  ip       text,
  role     text,          -- master | editor | null(실패)
  ok       boolean not null,
  action   text not null,
  post_id  bigint,
  author   text
);
create index if not exists board_log_ip_at_idx on public.board_log (ip, at desc);
alter table public.board_log enable row level security;

-- 4) 첨부 파일 버킷 — 공개 읽기, 파일당 50MB
--    올리기는 board-admin이 발급하는 서명 주소로만 한다(버킷에 쓰기 정책 없음).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'board-files', 'board-files', true, 52428800,
  array[
    'application/pdf',
    'application/x-hwp', 'application/haansofthwp', 'application/vnd.hancom.hwp',
    'application/hwp+zip', 'application/vnd.hancom.hwpx', 'application/haansofthwpx',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    'application/vnd.ms-powerpoint',
    'application/vnd.openxmlformats-officedocument.presentationml.presentation',
    'application/zip', 'application/x-zip-compressed',
    'image/png', 'image/jpeg', 'image/gif', 'image/webp',
    'text/plain', 'text/csv',
    'video/mp4',
    'application/octet-stream'
  ]
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- 확인
select 'board_posts' as t, count(*) from public.board_posts
union all select 'board_settings', count(*) from public.board_settings
union all select 'bucket', count(*) from storage.buckets where id = 'board-files';
